#!/usr/bin/env bun
// Materialize Cargo-ready Git packages from the same sources as registry releases.
import { readdirSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { prepare } from "./prepare-release";
import { ROOT, readConfig, readToml, run } from "./release-common";

const config = readToml(resolve(ROOT, "git-release.toml"));
const destination = resolve(ROOT, "packages");
prepare(readConfig(), config.version, destination);
for (const name of readConfig().crates) {
  const path = resolve(destination, name, "Cargo.toml");
  const manifest = readToml(path);
  const included = new Set(["src", "resources", "build.rs", "Cargo.toml", "README.md", "LICENSE", "NOTICE"]);
  for (const entry of readdirSync(resolve(destination, name))) {
    if (!included.has(entry)) rmSync(resolve(destination, name, entry), { recursive: true, force: true });
  }
  for (const group of [manifest, ...Object.values(manifest.target ?? {})] as any[]) {
    for (const section of ["dependencies", "build-dependencies"]) {
      if (group[section]?.wgpu) {
        Object.assign(group[section].wgpu, { git: config.wgpu.git, rev: config.wgpu.rev });
      }
    }
  }
  writeFileSync(path, "# Generated by script/prepare-git.ts; edit source manifests instead.\n" + Bun.TOML.stringify(manifest));
}
writeFileSync(resolve(destination, "SOURCE.json"), JSON.stringify({
  sourceRevision: run(["git", "log", "-1", "--format=%H", "--", "crates"], true).trim(),
  version: config.version,
  wgpu: config.wgpu,
  generator: "script/prepare-git.ts",
}, null, 2) + "\n");
